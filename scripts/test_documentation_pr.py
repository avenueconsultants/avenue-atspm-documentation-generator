"""PR preparation tests; no remote Git operations or PR creation."""
from argparse import Namespace
from contextlib import redirect_stdout
import io
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import prepare_documentation_pr as pr


URL = "https://github.com/example/utility"


class ComparisonTests(unittest.TestCase):
    def test_revision_and_timestamp_only_changes_are_ignored(self):
        old = (f"# Utility\n<small>Generated on yesterday</small>\n"
               f"[View source]({URL}/blob/old/Options.cs#L3)\n").encode()
        new = old.replace(b"yesterday", b"today").replace(b"/old/", b"/new/")
        self.assertFalse(pr.meaningful_change({"utility.md": old}, {"utility.md": new}, URL))
        self.assertTrue(pr.meaningful_change({"utility.md": old},
                                            {"utility.md": new + b"New description"}, URL))
        self.assertTrue(pr.meaningful_change({"utility.md": old},
                                            {"utility.md": new.replace(b"#L3", b"#L4")}, URL))

    def test_log_revisions_are_ignored_but_messages_and_defaults_are_not(self):
        old = f"| `1` | message | [Log.cs]({URL}/blob/old/Log.cs#L3) |\n".encode()
        new = old.replace(b"/old/", b"/new/")
        self.assertFalse(pr.meaningful_change({"log-messages.md": old}, {"log-messages.md": new}, URL))
        self.assertTrue(pr.meaningful_change({"log-messages.md": old},
                                            {"log-messages.md": new.replace(b"message", b"new message")}, URL))
        self.assertTrue(pr.meaningful_change({"utility.md": b"| default | old |"},
                                            {"utility.md": b"| default | new |"}, URL))
        self.assertTrue(pr.meaningful_change({"old.md": b"same"}, {"new.md": b"same"}, URL))

    def test_template_reference_revision_alone_does_not_create_pr(self):
        old = f"# Configuration templates\nSource revision: [old]({URL}/tree/old).\n".encode()
        new = old.replace(b"old", b"new")
        self.assertFalse(pr.meaningful_change({"configuration-templates.md": old},
                                              {"configuration-templates.md": new}, URL))
        self.assertTrue(pr.meaningful_change({"configuration-templates.md": old},
                                             {"configuration-templates.md": new + b"New setting"}, URL))

    def test_paths_and_branch_identity(self):
        for value in ("../docs", "/docs", ".git", "docs/*", "docs\nsecret", "a/../b", "C:/docs"):
            with self.subTest(value=value), self.assertRaises(ValueError):
                pr.relative_path(value)
        self.assertEqual("docs/Generated Docs", pr.relative_path("docs/Generated Docs"))
        self.assertEqual(pr.branch_name("development", "docs"), pr.branch_name("development", "docs"))
        self.assertNotEqual(pr.branch_name("development", "docs"), pr.branch_name("main", "docs"))


class PreparationTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        root = Path(self.temp.name)
        self.source = root / "source"
        self.target = root / "target"
        self.source.mkdir()
        self.target.mkdir()
        self.source_file = self.source / "Options.cs"
        self.source_file.write_text('[ConfigurationSection("Utility")]\n'
                                   'public class Options { public int Port { get; set; } = 123; }', encoding="utf-8")
        self.map = {"schemaVersion": 2, "productName": "Utility", "sourcePaths": ["."],
                    "containers": [{"name": "Utility", "slug": "utility", "sections": [], "autoDiscover": True}]}
        self.save_map()
        self.revision = "a" * 40
        self.counter = 0
        self.real_run = pr.run

    def save_map(self):
        for root in (self.source, self.target):
            (root / "documentation.json").write_text(json.dumps(self.map), encoding="utf-8")

    def run_command(self, *args, env=None):
        if args[0] == "git":
            return "2026-10-02T00:00:00Z" if "show" in args else self.revision
        return self.real_run(*args, env=env)

    def prepare(self, sync="", command=None):
        self.counter += 1
        args = Namespace(source=self.source, target=self.target, target_branch="development",
                         config="documentation.json", output="docs/autogenerated",
                         repository_url=URL, sync_container=sync,
                         artifacts=Path(self.temp.name) / f"preview-{self.counter}")
        with patch.object(pr, "run", side_effect=command or self.run_command), redirect_stdout(io.StringIO()):
            return pr.prepare(args)

    def test_first_run_repeat_run_and_configuration_change(self):
        self.assertTrue(self.prepare())
        output = self.target / "docs/autogenerated"
        initial_body = (Path(self.temp.name) / "preview-1/pr-body.md").read_text(encoding="utf-8")
        self.assertIn("Initial baseline", initial_body)
        before = pr.files(output)
        self.revision = "b" * 40
        self.assertFalse(self.prepare())
        self.assertEqual(before, pr.files(output))
        unchanged_body = (Path(self.temp.name) / "preview-2/pr-body.md").read_text(encoding="utf-8")
        self.assertIn("No new modeled configuration changes", unchanged_body)
        self.source_file.write_text(self.source_file.read_text().replace("123", "456"), encoding="utf-8")
        self.assertTrue(self.prepare())
        self.assertIn("456", (output / "configuration-changes.md").read_text())
        body = (Path(self.temp.name) / "preview-3/pr-body.md").read_text(encoding="utf-8")
        self.assertIn("Default changed", body)
        self.assertIn("Utility.Port", body)
        self.assertIn("Utility__Port", body)
        self.assertIn("`123` → `456`", body)
        self.assertFalse((self.target / "Options.cs").exists())
        self.assertTrue((Path(self.temp.name) / "preview-3/site/index.html").is_file())

    def test_failed_site_validation_preserves_target(self):
        self.assertTrue(self.prepare())
        before = pr.files(self.target / "docs/autogenerated")
        self.source_file.write_text(self.source_file.read_text().replace("123", "456"), encoding="utf-8")
        def fail_site(*args, env=None):
            if "mkdocs" in args:
                raise RuntimeError("Simulated strict site validation failure")
            return self.run_command(*args, env=env)
        with self.assertRaisesRegex(RuntimeError, "strict site"):
            self.prepare(command=fail_site)
        self.assertEqual(before, pr.files(self.target / "docs/autogenerated"))

    def test_corrupt_snapshot_and_unmanaged_files_preserve_target(self):
        self.prepare()
        output = self.target / "docs/autogenerated"
        (output / "configuration-snapshot.json").write_text("{broken", encoding="utf-8")
        before = pr.files(output)
        with self.assertRaises(RuntimeError):
            self.prepare()
        self.assertEqual(before, pr.files(output))
        (output / "handwritten.md").write_text("Keep this", encoding="utf-8")
        before = pr.files(output)
        with self.assertRaises(RuntimeError):
            self.prepare()
        self.assertEqual(before, pr.files(output))

    def test_explicit_map_sync_is_proposed_then_stable(self):
        self.map["containers"][0].update(autoDiscover=False, sections=["Utility"])
        self.save_map()
        self.source_file.write_text(self.source_file.read_text() +
                                   '\n[ConfigurationSection("Extra")] public class Extra { public bool Enabled { get; set; } }',
                                   encoding="utf-8")
        with self.assertRaises(RuntimeError):
            self.prepare()
        self.assertTrue(self.prepare(sync="utility"))
        source_map = self.source / "documentation.json"
        target_map = self.target / "documentation.json"
        self.assertEqual(source_map.read_bytes(), target_map.read_bytes())
        self.assertIn("Extra", json.loads(target_map.read_text())["containers"][0]["sections"])
        self.assertFalse(self.prepare(sync="utility"))

    def test_sync_rejects_divergent_target_map(self):
        self.map["containers"][0].update(autoDiscover=False, sections=["Utility"])
        self.save_map()
        target_map = self.target / "documentation.json"
        target_map.write_text(target_map.read_text().replace('"Utility"', '"Other"'), encoding="utf-8")
        before = target_map.read_bytes()
        self.source_file.write_text(self.source_file.read_text() +
                                   '\n[ConfigurationSection("Extra")] public class Extra { public int Count { get; set; } }',
                                   encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "differs between source and target"):
            self.prepare(sync="utility")
        self.assertEqual(before, target_map.read_bytes())
        self.assertFalse((self.target / "docs").exists())


if __name__ == "__main__":
    unittest.main()
