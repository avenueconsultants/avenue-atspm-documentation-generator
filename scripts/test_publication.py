"""Publication checks operate on reviewed files and never deploy."""
from __future__ import annotations

import json
from pathlib import Path
import subprocess
import tempfile
import unittest
import yaml

from validate_publication import validate
from site_configuration import ROOT


URL = "https://github.com/example/utility"
GENERATOR_REF = "b" * 40


class PublicationTests(unittest.TestCase):
    def test_workflow_keeps_deployment_opt_in_and_uses_checked_out_commit(self):
        shared = yaml.load((ROOT / ".github/workflows/documentation-pages.yml").read_text(encoding="utf-8"),
                           Loader=yaml.BaseLoader)
        caller = yaml.load((ROOT / "integration/publish-documentation-pages.yml").read_text(encoding="utf-8"),
                           Loader=yaml.BaseLoader)
        self.assertEqual("false", shared["on"]["workflow_call"]["inputs"]["publish"]["default"])
        self.assertEqual("true", caller["jobs"]["pages"]["with"]["publish"])
        self.assertEqual("inputs.publish", shared["jobs"]["deploy"]["if"])
        self.assertEqual("${{ github.sha }}", shared["jobs"]["build"]["steps"][1]["with"]["ref"])
        generator_checkout = shared["jobs"]["build"]["steps"][2]["with"]
        self.assertEqual("${{ job.workflow_repository }}", generator_checkout["repository"])
        self.assertEqual("${{ job.workflow_sha }}", generator_checkout["ref"])

    def test_consumer_workflows_use_root_map_and_review_before_publication(self):
        pr_workflow = yaml.load((ROOT / ".github/workflows/documentation-pr.yml").read_text(encoding="utf-8"),
                                Loader=yaml.BaseLoader)
        pr_caller = yaml.load((ROOT / "integration/update-documentation.yml").read_text(encoding="utf-8"),
                              Loader=yaml.BaseLoader)
        pages_caller = yaml.load((ROOT / "integration/publish-documentation-pages.yml").read_text(encoding="utf-8"),
                                 Loader=yaml.BaseLoader)
        action = yaml.load((ROOT / "action.yml").read_text(encoding="utf-8"), Loader=yaml.BaseLoader)
        self.assertEqual("documentation.json", action["inputs"]["config-file"]["default"])
        self.assertEqual("documentation.json", pr_workflow["on"]["workflow_call"]["inputs"]["config-file"]["default"])
        self.assertNotIn("generator-ref", pr_workflow["on"]["workflow_call"]["inputs"])
        self.assertNotIn("generator-ref", pr_caller["jobs"]["documentation"]["with"])
        self.assertEqual("avenueconsultants/avenue-atspm-documentation-generator/.github/workflows/documentation-pr.yml@feature/generic-documentation-test", pr_caller["jobs"]["documentation"]["uses"])
        self.assertEqual("avenueconsultants/avenue-atspm-documentation-generator/.github/workflows/documentation-pages.yml@feature/generic-documentation-test", pages_caller["jobs"]["pages"]["uses"])
        pr_checkout = next(step["with"] for step in pr_workflow["jobs"]["documentation"]["steps"]
                           if step.get("name") == "Check out the exact generator workflow revision")
        self.assertEqual("${{ job.workflow_repository }}", pr_checkout["repository"])
        self.assertEqual("${{ job.workflow_sha }}", pr_checkout["ref"])
        self.assertEqual("true", pr_caller["jobs"]["documentation"]["with"]["create-pr"])
        self.assertEqual("false", pr_workflow["jobs"]["documentation"]["steps"][-1]["with"]["draft"])
        self.assertEqual("true", pages_caller["jobs"]["pages"]["with"]["publish"])
        self.assertEqual(["docs/autogenerated/**"], pages_caller["on"]["push"]["paths"])

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.output = self.root / "docs/autogenerated"
        self.output.mkdir(parents=True)
        config = self.root / "documentation.json"
        config.write_text(json.dumps({
            "schemaVersion": 2, "productName": "Utility", "sourcePaths": ["."],
            "containers": [{"name": "Utility", "slug": "utility", "sections": ["Utility"]}]
        }), encoding="utf-8")
        managed = {"index.md", "configuration-changes.md", "configuration-templates.md",
                   "configuration-snapshot.json", "utility.md", "utility.example.json",
                   "utility.env.example"}
        managed = {"support/" + name if name not in ("index.md", "utility.md") else name for name in managed}
        for name in managed:
            (self.output / name).parent.mkdir(parents=True, exist_ok=True)
            (self.output / name).write_text("Example\n", encoding="utf-8")
        (self.output / "support/configuration-snapshot.json").write_text(json.dumps({
            "repositoryUrl": URL, "sourceRevision": "a" * 40
        }), encoding="utf-8")
        (self.output / "support/utility.example.json").write_text('{"Utility":{"Port":123}}', encoding="utf-8")
        (self.output / "support/.atspm-docs-generator.json").write_text(json.dumps({
            "Generator": "atspm-documentation-generator", "ManagedFiles": sorted(managed)
        }), encoding="utf-8")
        subprocess.run(["git", "init", "-q", str(self.root)], check=True)
        subprocess.run(["git", "-C", str(self.root), "-c", "user.name=Test", "-c",
                        "user.email=test@example.com", "add", "-A"], check=True)
        subprocess.run(["git", "-C", str(self.root), "-c", "user.name=Test", "-c",
                        "user.email=test@example.com", "commit", "-qm", "Reviewed docs"], check=True)
        self.revision = subprocess.check_output(["git", "-C", str(self.root), "rev-parse", "HEAD"], text=True).strip()

    def check(self):
        return validate(self.root, "documentation.json", "docs/autogenerated",
                        URL, self.revision, GENERATOR_REF)

    def test_committed_files_and_provenance_are_accepted(self):
        review = self.check()
        self.assertIn(self.revision, review)
        self.assertIn("a" * 40, review)
        self.assertIn("Generated files: 8", review)

    def test_changed_or_untracked_files_cannot_publish(self):
        (self.output / "utility.md").write_text("Changed", encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "differs from the checked-out commit"):
            self.check()
        (self.output / "utility.md").write_text("Example\n", encoding="utf-8")
        (self.output / "other.md").write_text("Extra", encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "differs from the checked-out commit"):
            self.check()

    def test_missing_file_or_wrong_source_repository_fails(self):
        (self.output / "support/utility.example.json").unlink()
        with self.assertRaisesRegex(ValueError, "differs from the checked-out commit"):
            self.check()
        with self.assertRaisesRegex(ValueError, "missing="):
            validate(self.root, "documentation.json", "docs/autogenerated",
                     URL, self.revision, GENERATOR_REF, require_committed=False)
        (self.output / "support/utility.example.json").write_text("{}", encoding="utf-8")
        with self.assertRaisesRegex(ValueError, "Snapshot source repository"):
            validate(self.root, "documentation.json", "docs/autogenerated",
                     "https://github.com/example/other", self.revision, GENERATOR_REF, require_committed=False)

    def test_previously_reviewed_flat_layout_remains_publishable(self):
        support = self.output / "support"
        manifest_path = support / ".atspm-docs-generator.json"
        manifest = json.loads(manifest_path.read_text())
        manifest["ManagedFiles"] = [name.removeprefix("support/") for name in manifest["ManagedFiles"]]
        manifest_path.write_text(json.dumps(manifest), encoding="utf-8")
        for path in support.iterdir():
            path.rename(self.output / path.name)
        support.rmdir()
        self.assertIn("Generated files: 8", validate(self.root, "documentation.json", "docs/autogenerated",
                      URL, self.revision, GENERATOR_REF, require_committed=False))


if __name__ == "__main__":
    unittest.main()
